const tokenize = (value) => normalizeAssistantText(value)
  .split(' ')
  .map((token) => token.trim())
  .filter((token) => token.length > 1);

const includesNormalized = (text, value) => {
  const normalizedValue = normalizeAssistantText(value);
  return Boolean(normalizedValue && text.includes(normalizedValue));
};

const scoreKnowledgeEntry = (message, entry) => {
  const normalizedMessage = normalizeAssistantText(message);
  if (!normalizedMessage) return 0;

  let score = 0;
  const questions = Array.isArray(entry.questions) ? entry.questions : [];
  const keywords = Array.isArray(entry.keywords) ? entry.keywords : [];

  questions.forEach((question) => {
    const normalizedQuestion = normalizeAssistantText(question);
    if (!normalizedQuestion) return;
    if (normalizedMessage === normalizedQuestion) score += 40;
    else if (normalizedMessage.includes(normalizedQuestion) || normalizedQuestion.includes(normalizedMessage)) score += 20;
  });

  keywords.forEach((keyword) => {
    if (!includesNormalized(normalizedMessage, keyword)) return;
    score += normalizeAssistantText(keyword).length > 5 ? 8 : 4;
  });

  const messageTokens = new Set(tokenize(normalizedMessage));
  const entryTokens = new Set(tokenize([...questions, ...keywords].join(' ')));
  messageTokens.forEach((token) => {
    if (entryTokens.has(token)) score += 2;
  });

  return score;
};

export const getRelatedQuestions = (questions = [], currentQuestion = '') => {
  const current = normalizeAssistantText(currentQuestion);
  const seen = new Set();

  return questions
    .filter((question) => {
      const normalized = normalizeAssistantText(question);
      if (!normalized || normalized === current || seen.has(normalized)) return false;
      seen.add(normalized);
      return true;
    })
    .slice(0, 5);
};

export const findAssistantKnowledgeEntry = (message) => {
  const scored = AI_KNOWLEDGE_BASE
    .map((entry) => ({ entry, score: scoreKnowledgeEntry(message, entry) }))
    .filter((item) => item.score >= 4)
    .sort((left, right) => right.score - left.score);

  return scored[0]?.entry || null;
};

export const createAssistantKnowledgeResponse = (message, { fallbackToGeneral = false } = {}) => {
  const entry = findAssistantKnowledgeEntry(message);

  if (entry) {
    return {
      text: entry.answer,
      relatedQuestions: getRelatedQuestions(entry.related, message),
      knowledgeId: entry.id,
    };
  }

  if (!fallbackToGeneral) return null;

  return {
    text: 'ممكن توضح سؤالك أكثر؟ أقدر أساعدك في الشحن، طرق الدفع، متابعة الطلبات، المنتجات، أو مشاكل الرصيد.',
    relatedQuestions: getRelatedQuestions(GENERAL_ASSISTANT_QUESTIONS, message),
    knowledgeId: 'general_fallback',
  };
};

export const createRelatedQuestionsForMessage = (message, fallbackQuestions = GENERAL_ASSISTANT_QUESTIONS) => {
  const entry = findAssistantKnowledgeEntry(message);
  return getRelatedQuestions(entry?.related?.length ? entry.related : fallbackQuestions, message);
};
